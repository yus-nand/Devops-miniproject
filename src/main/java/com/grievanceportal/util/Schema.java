package com.grievanceportal.util;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/** Creates the tables if they do not exist yet. */
public final class Schema {

    private Schema() {
    }

    public static void init() throws SQLException {
        try (Connection c = Database.getConnection(); Statement s = c.createStatement()) {
            s.execute("CREATE TABLE IF NOT EXISTS users ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "username VARCHAR(50) NOT NULL UNIQUE, "
                    + "password_hash VARCHAR(255) NOT NULL, "
                    + "full_name VARCHAR(100) NOT NULL, "
                    + "role VARCHAR(20) NOT NULL)");

            s.execute("CREATE TABLE IF NOT EXISTS grievances ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "ref_no VARCHAR(20) NOT NULL UNIQUE, "
                    + "policyholder_id BIGINT NOT NULL, "
                    + "assigned_officer_id BIGINT, "
                    + "policy_number VARCHAR(30) NOT NULL, "
                    + "category VARCHAR(30) NOT NULL, "
                    + "title VARCHAR(150) NOT NULL, "
                    + "description VARCHAR(2000) NOT NULL, "
                    + "status VARCHAR(20) NOT NULL, "
                    + "resolution_note VARCHAR(1000), "
                    + "created_on DATE NOT NULL, "
                    + "due_on DATE NOT NULL, "
                    + "FOREIGN KEY (policyholder_id) REFERENCES users(id), "
                    + "FOREIGN KEY (assigned_officer_id) REFERENCES users(id))");

            s.execute("CREATE TABLE IF NOT EXISTS status_history ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "grievance_id BIGINT NOT NULL, "
                    + "from_status VARCHAR(20), "
                    + "to_status VARCHAR(20) NOT NULL, "
                    + "changed_by BIGINT NOT NULL, "
                    + "note VARCHAR(1000), "
                    + "changed_at TIMESTAMP NOT NULL, "
                    + "FOREIGN KEY (grievance_id) REFERENCES grievances(id), "
                    + "FOREIGN KEY (changed_by) REFERENCES users(id))");
        }
    }
}